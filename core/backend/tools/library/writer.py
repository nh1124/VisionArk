from typing import Any, List, Dict, Optional
from pydantic import BaseModel, Field
from tools.base import BaseTool
from tools.utils import resolve_project_artifacts_dir
from utils.paths import get_project_dir, secure_path_join
from llm import get_provider
from llm.base_provider import Message
import json
import asyncio
from datetime import datetime

class RecursiveWriterArgs(BaseModel):
    topic: str = Field(..., description="The main topic or title of the long-form content.")
    target_file: str = Field(..., description="Relative path to save the final content (e.g., 'artifacts/book.md').")
    depth: Optional[int] = Field(3, description="Depth of the outline (not yet fully utilized, reserved for future recursion).")

class RecursiveWriterTool(BaseTool):
    name = "recursive_writer"
    description = (
        "Generate very long content (reports, books) by breaking it down into sections. "
        "It automatically generates an outline, then writes each section recursively to avoid token limits. "
        "HOW TO USE: 'recursive_writer(topic=\"History of Rome\", target_file=\"artifacts/rome_history.md\")'."
    )
    args_schema = RecursiveWriterArgs

    async def run(self, topic: str, target_file: str, depth: int = 3, **kwargs) -> Any:
        user_id: str = kwargs.get("user_id")
        project_id: str = kwargs.get("project_id")
        api_key: str = kwargs.get("api_key")
        db_session = kwargs.get("db_session")
        
        if not user_id or not project_id:
            return {"success": False, "message": "Context error: Missing user_id or project_id"}
            
        if not api_key and db_session:
            from tools.utils import get_user_api_key
            api_key = await get_user_api_key(user_id, db_session)

        self.llm = get_provider(api_key=api_key)
        
        # 1. Resolve Target Path
        try:
            root_dir = get_project_dir(user_id, project_id)
            if target_file.startswith("artifacts/"):
                final_path = secure_path_join(root_dir, target_file)
            else:
                artifacts_dir = await resolve_project_artifacts_dir(user_id, project_id, kwargs.get("db_session"))
                final_path = secure_path_join(artifacts_dir, target_file)
                
            final_path.parent.mkdir(parents=True, exist_ok=True)
            # Clear file initially
            final_path.write_text(f"# {topic}\n\n*Generated by RecursiveWriterTool on {datetime.now()}*\n\n", encoding='utf-8')
        except Exception as e:
            return {"success": False, "message": f"Path resolution failed: {e}"}

        # 2. Generate Outline
        if self.status_callback:
            await self.status_callback(f"Generating outline for '{topic}'...", "processing")
            
        outline = await self._generate_outline(topic)
        if not outline:
            return {"success": False, "message": "Failed to generate outline."}
        
        # Write Outline to file first
        toc_text = "## Table of Contents\n\n" + "\n".join([f"- {item['title']}" for item in outline]) + "\n\n---\n\n"
        with open(final_path, "a", encoding="utf-8") as f:
            f.write(toc_text)

        # 3. Recursive Writing
        previous_context = "Start of the document."
        total_sections = len(outline)
        
        for i, section in enumerate(outline):
            section_title = section['title']
            section_desc = section.get('description', '')
            
            if self.status_callback:
                await self.status_callback(f"Writing section {i+1}/{total_sections}: {section_title}...", "processing")
            
            # Write Section
            content = await self._write_section(topic, section_title, section_desc, previous_context)
            
            # Save to file
            with open(final_path, "a", encoding="utf-8") as f:
                f.write(content + "\n\n")
            
            # Summarize for next context
            previous_context = await self._summarize_context(section_title, content)
            
        return {
            "success": True, 
            "message": f"Successfully wrote long-form content to {target_file}",
            "data": {"path": target_file}
        }

    async def _generate_outline(self, topic: str) -> List[Dict]:
        """Generate a structured outline using LLM"""
        prompt = f"""Create a detailed outline for a long comprehensive report on: "{topic}".
        Return ONLY a JSON array of objects, where each object has 'title' and 'description'.
        Example:
        [
            {{"title": "Introduction", "description": "Overview of the topic..."}},
            {{"title": "Chapter 1", "description": "Deep dive into..."}}
        ]
        """
        messages = [
            Message(role="system", content="You are a planning assistant. Output valid JSON only."),
            Message(role="user", content=prompt)
        ]
        
        try:
            response = await self.llm.complete_async(messages, temperature=0.5, json_mode=True)
            text = response.content
            # Clean generic markdown ticks if present
            if "```json" in text:
                text = text.split("```json")[1].split("```")[0].strip()
            elif "```" in text:
                text = text.split("```")[1].split("```")[0].strip()
                
            return json.loads(text)
        except Exception as e:
            print(f"[RecursiveWriter] Outline generation failed: {e}")
            return []

    async def _write_section(self, topic: str, title: str, description: str, prev_context: str) -> str:
        """Write a specific section based on context"""
        prompt = f"""You are writing a section of a report on "{topic}".
        
        Current Section: "{title}"
        Description: {description}
        
        Context from previous sections:
        {prev_context}
        
        Task: Write the content for ONLY this section. 
        - Use Markdown.
        - Start with the section header (## {title}).
        - Be comprehensive and detailed.
        - Do not include "In conclusion" or wrap up the whole book, just this section.
        """
        
        messages = [
            Message(role="system", content="You are an expert ghostwriter. Write detailed, engaging content."),
            Message(role="user", content=prompt)
        ]
        
        response = await self.llm.complete_async(messages, temperature=0.7)
        return response.content

    async def _summarize_context(self, title: str, content: str) -> str:
        """Create a short summary of what was just written to pass to the next step"""
        prompt = f"""Summarize the following section so the writer of the NEXT section knows what has been covered.
        Keep it brief (under 100 words).
        
        Section: {title}
        Content:
        {content[:4000]} # Truncate if too long
        """
        
        messages = [
            Message(role="user", content=prompt)
        ]
        
        response = await self.llm.complete_async(messages, temperature=0.3)
        return response.content
