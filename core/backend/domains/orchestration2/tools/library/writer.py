"""Writer tool: recursive long-form content generation."""

from __future__ import annotations

import json
from datetime import datetime

from domains.orchestration2.engine.models.execution import ExecutionContext, ToolResult
from domains.orchestration2.engine.models.message import Message, ToolCallRef
from domains.orchestration2.engine.models.common import MessageRole
from domains.orchestration2.engine.models.tool import ToolDef
from domains.orchestration2.tools.base import (
    fail,
    get_project_id,
    get_user_api_key,
    get_user_id,
    make_result,
    resolve_artifacts_dir,
)
from shared.paths import get_project_dir, secure_path_join


class RecursiveWriterTool:
    definition = ToolDef(
        name="recursive_writer",
        description=(
            "Generate very long content (reports, books) by breaking it down into sections. "
            "Automatically generates an outline, then writes each section to avoid token limits. "
            "HOW TO USE: recursive_writer(topic=\"History of Rome\", target_file=\"artifacts/rome.md\")"
        ),
        parameters={
            "type": "object",
            "properties": {
                "topic": {"type": "string", "description": "Main topic or title"},
                "target_file": {"type": "string", "description": "Relative path to save content"},
                "depth": {"type": "integer", "description": "Outline depth (reserved)"},
            },
            "required": ["topic", "target_file"],
        },
    )

    async def invoke(self, call: ToolCallRef, ctx: ExecutionContext) -> ToolResult:
        topic = call.arguments.get("topic", "")
        target_file = call.arguments.get("target_file", "")
        user_id = get_user_id(ctx)
        project_id = get_project_id(ctx)

        try:
            api_key = await get_user_api_key(ctx)
            if not api_key:
                return fail(call, "No API key available for content generation.")

            from infrastructure.llm.provider_registry import resolve_provider
            # Determine provider from the engine kind in execution context
            provider_id = getattr(ctx, 'engine_kind', 'gemini') or 'gemini'
            provider = resolve_provider(provider_id, api_key)

            # Resolve path
            root_dir = get_project_dir(user_id, project_id)
            if target_file.startswith("artifacts/"):
                final_path = secure_path_join(root_dir, target_file)
            else:
                artifacts_dir = await resolve_artifacts_dir(ctx)
                final_path = secure_path_join(artifacts_dir, target_file)

            final_path.parent.mkdir(parents=True, exist_ok=True)
            final_path.write_text(
                f"# {topic}\n\n*Generated by RecursiveWriterTool on {datetime.now()}*\n\n",
                encoding="utf-8",
            )

            # Generate outline
            outline = await self._generate_outline(provider, topic)
            if not outline:
                return fail(call, "Failed to generate outline.")

            toc = "## Table of Contents\n\n" + "\n".join(f"- {s['title']}" for s in outline) + "\n\n---\n\n"
            with open(final_path, "a", encoding="utf-8") as f:
                f.write(toc)

            # Write sections
            prev_context = "Start of the document."
            for i, section in enumerate(outline):
                content = await self._write_section(provider, topic, section["title"], section.get("description", ""), prev_context)
                with open(final_path, "a", encoding="utf-8") as f:
                    f.write(content + "\n\n")
                prev_context = await self._summarize(provider, section["title"], content)

            return make_result(call, f"Long-form content written to {target_file}")
        except Exception as e:
            return fail(call, f"Writer failed: {e}")

    async def _generate_outline(self, provider, topic: str) -> list[dict]:
        prompt = (
            f'Create a detailed outline for: "{topic}". '
            "Return ONLY a JSON array of objects with 'title' and 'description'."
        )
        messages = [Message(role=MessageRole.USER, content=prompt)]
        try:
            response = await provider.complete(
                messages,
                system="You are a planning assistant. Output valid JSON only.",
            )
            text = response.content
            if "```json" in text:
                text = text.split("```json")[1].split("```")[0].strip()
            elif "```" in text:
                text = text.split("```")[1].split("```")[0].strip()
            return json.loads(text)
        except Exception:
            return []

    async def _write_section(self, provider, topic: str, title: str, desc: str, prev: str) -> str:
        prompt = (
            f'Writing section of report on "{topic}".\n'
            f'Section: "{title}"\nDescription: {desc}\n'
            f"Previous context: {prev}\n\n"
            f"Write ONLY this section. Use Markdown. Start with ## {title}."
        )
        messages = [Message(role=MessageRole.USER, content=prompt)]
        response = await provider.complete(
            messages,
            system="You are an expert ghostwriter.",
        )
        return response.content

    async def _summarize(self, provider, title: str, content: str) -> str:
        prompt = f"Summarize this section briefly (under 100 words):\n\nSection: {title}\n{content[:4000]}"
        messages = [Message(role=MessageRole.USER, content=prompt)]
        response = await provider.complete(messages)
        return response.content
